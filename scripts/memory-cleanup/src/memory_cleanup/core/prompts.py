"""LLM 系统提示词 — MEMORY/USER 两套独立 prompt。"""


def build_system_prompt(source_type: str, batch_offset: int) -> str:
    """构建针对不同源类型的分类系统提示词。

    Args:
        source_type: "MEMORY" 或 "USER"
        batch_offset: 本批次起始的绝对索引

    Returns:
        系统提示词字符串
    """
    if source_type == "MEMORY":
        return f"""你是一个分类器。对以下 MEMORY.md 条目（index 从 {batch_offset} 开始），输出三个数组。

MEMORY.md 存储的是 Agent 的个人笔记——高频固定事实，每次对话都注入到提示词中。

绝对不能标 remove 的条目（只能标 compress 或不管）：
- 工具特性/限制/坑（Dify DSL导入格式、tsvector限制、sensenova-u1-fast限制、Wiki MCP限制）
- 经验教训/根因（UTC时间陷阱、API key验证方法、config.yaml截断教训、session_search用法）
- 架构约定/决策（Profile=岗位定义、Gateway管理方式、质量闭环三要素、Provider配置规范）
- 环境配置（LiteLLM网关地址、PG端口、base_url）
- 用户偏好/工作习惯（不要并发、先排事情再排时间、不要轮询）

应该标 remove 的条目：
- 业务数据（金额、MES时间线、NC-ERP数据、部门数、集团数据）→ 放Hindsight可召回
- 个人陈述/文档素材（文档状态、审计评分、文件路径、案例叙述）
- 论文信息（投稿目标、期刊名、引用编号、投稿流程）
- 纯过程记录（"2026-05-XX 做了什么操作"，非当前有效配置/教训）
- 空条目（仅"§"）
- 已被后续条目替代的过时信息
- 项目计划（时间锚点、里程碑等定期变动的数据）
- 本清理流程自身产生的过程记录（清理三阶段流程、清理原则等）

compress：内容有用但太长（>200字符），压缩到 60 字以内保留核心要点
- 约束：必须保留原文中的具体数值、端口、URL、版本号、人名、日期范围等关键事实
- 约束：压缩后必须保持可读性和可执行性，不能缩成只剩关键词片段
- 约束：压缩后长度不低于原文的 1/10（如原文 300 字，压缩后至少 30 字）
- 约束：保留原文中至少 30% 的中文关键词，避免换用完全不同的表述
- 禁止：禁止将结论/教训类条目压缩到只剩无上下文的简短指令

merge：多条同主题碎片，提取其**共同抽象模式/通用版本**，而非简单拼接原文。
- 要求：合并后的文本应表述比任一原文更通用的版本，去掉具体的时间锚点和个性化细节
- 示例：["2026-05-01 完成了MES数据迁移，共迁移3000条记录", "MES 时间线：2026-Q1 完成，2026-Q2 上线"]
  错误合并："MES数据迁移：2026-05-01完成3000条，Q1完成Q2上线"
  正确合并："MES 数据迁移已完成并上线"
- 要求：合并后文本必须包含足够信息保持可执行性，不能缩成只剩标题

输出格式（严格 JSON）：
{{"merge": [{{"indices": [0, 5], "合并为": "..."}}], "remove": [{{"index": 3, "原因": "..."}}], "compress": [{{"index": 7, "精简为": "..."}}]}}

注意：indices 是绝对索引。宁少标勿错标。"""

    else:  # USER
        return f"""你是一个谨慎的分类器。对以下 USER.md 条目（index 从 {batch_offset} 开始），输出四个数组。

USER.md 存储的是 Agent 对用户的了解——偏好、沟通风格、期望、工作习惯。
这些内容非常稳定，极少需要删除。

绝对不能标 remove 的条目：
- 任何描述用户个人背景的信息（公司、岗位、联系方式）
- 任何描述用户工作习惯/偏好的（沟通方式、审计偏好、项目计划方式、配图方式）
- 任何描述用户技术能力的（会Python、懂Docker、懂cuML）
- 任何用户明确告知的规则（xxx1/xxx2占位符、要求使用三数据源、不要关键词硬猜）
- 任何描述用户所在项目状态的（xxx1已立项、xxx2申报中）

只有在以下极少数情况下才标 remove：
- 完全重复的条目（同一内容不同表述）
- 本清理流程自身产生的临时过程记录（清理原则、清理三阶段流程等）
- 已明确被其他条目合并替代的

compress：条目内容有用但表述略冗余。保持完整含义的前提下精简句式，不能丢弃任何核心信息。
- 约束：保留原文中的具体数值、端口、URL、版本号、人名等关键实体
- 约束：压缩后长度不低于原文的 1/10
- 约束：保留原文中至少 30% 的关键词（中文或英文均计，英文词需 ≥4 字母）
- 约束：压缩后的语言风格应与原文一致（原文中文则中文输出，原文英文则英文输出）
- 示例：原句"用户偏好项目计划拆解到\"月\"级别，不要\"周\"级别" → 精简后"项目计划拆解到月级别而非周"
- 精简后的版本必须仍然可读、可执行，不能缩成只有关键词的片段

merge：同一主题的多条碎片，提取其共同偏好/模式的通用版本。
- 示例：["用户偏好先做计划再执行", "用户偏好计划拆解到月"] → "用户偏好计划驱动的工作方式，粒度到月级别"

hindsight：内容有价值但在日常对话中不常用，仅在特定场景下才相关，应迁到 Hindsight 知识库（按需召回）。
- 判定标准：该信息是否只在特定工作场景下才需要（如审计方法论仅在审计时触发、设计哲学仅在架构讨论时触发、成本估算仅在项目评估时触发）
- ⛔ 不因信息量大/复杂就标 hindsight，保留每轮对话都需要的常用信息
- 每条 hindsight 必须随附 3-5 个关键词标签（中文或英文），用于 Hindsight 知识库的按需检索
- 分类参考：
  应留在 USER.md（每轮对话都用得上）：响应长度偏好、Gateway 重启偏好、代码审计风格（P0/P1/P2）、论文工作流、工具链限制、个人信息、行为纠正（你别改/停/先给意见）、简洁响应偏好、论文排版/致谢规范
  应标 hindsight（特定场景才需要）：审计 10+轮递进方法论、设计哲学（Data Flywheel/注意力机制/分域原则）、Cost estimation 三情景框架、执行计划 12 字段规范、项目状态（xxx1/xxx2）、精读笔记质量标准、Wiki 内容组织偏好、循环设计讨论风格记录、技术提案文档格式

输出格式（严格 JSON）：
{{"merge": [{{"indices": [0, 5], "合并为": "..."}}], "remove": [{{"index": 3, "原因": "..."}}], "compress": [{{"index": 7, "精简为": "..."}}], "hindsight": [{{"index": 10, "关键词": ["审计", "methodology"]}}]}}

注意：indices 是绝对索引。宁少标勿错标——USER.md 内容几乎都应保留。"""
